function applyArabicDiacritics(text: string): string {
  const words = text.split(/(\s+|[.,،؛!؟])/);
  return words
    .map((token) => {
      const clean = token.replace(/[.,،؛!؟]/g, '');
      if (DIACRITICS_MAP[clean]) {
        return token.replace(clean, DIACRITICS_MAP[clean]);
      }
      return token;
    })
    .join('');
}

/**
 * Parses raw Arabic speech text into paragraphs with realistic AI suggestions
 * strictly adhering to user's selected preferences.
 */
export function analyzeSpeechText(
  title: string,
  rawText: string,
  preferences: AnalysisPreferences = DEFAULT_ANALYSIS_PREFERENCES
): SpeechParagraph[] {
  const rawParagraphs = rawText
    .split(/\n\s*\n|\n/)
    .map((p) => p.trim())
    .filter((p) => p.length > 0);

  if (rawParagraphs.length === 0) {
    return [];
  }

  const tonePool = [
    'نبرة رصينة ومرحبة',
    'نبرة حماسية وملهمة',
    'نبرة استفسارية تشويقية',
    'نبرة حازمة وحاسمة',
    'نبرة هادئة ورصينة',
    'نبرة ختامية وقورة ومؤثرة',
  ];

  const pacingPool: Array<SpeechParagraph['speedPacing']> = [
    'بطيء ومتزن',
    'معتدل طبيعي',
    'سريع وحيوي',
    'معتدل طبيعي',
  ];

  const pacingNotes = [
    'ابدأ بتأنٍ واضح وأعطِ كل كلمة حقها لإشعار الجمهور بالأمان والهدوء.',
    'تدرج في الإيقاع والصوت مع تصاعد الفكرة لإبقاء الحضور في حالة يقظة تامة.',
    'أبطئ السرعة هنا تحديدًا فالعبارة تحمل المعنى الجوهري للخطاب.',
    'سرعة معتدلة مع تنفس عميق بعد كل جملة مكتملة المعنى.',
    'اختم بنبرة متزنة وثابتة تمنح كلماتك الأخيرة وزناً لا يُنسى.',
  ];

  const presenceTips = [
    'وزع نظراتك بين يمين ويسار القاعة بالتساوي مع ابتسامة دافئة وخفيفة.',
    'استخدم إشارات اليدين المفتوحة للأعلى للإيحاء بالمشاركة والشفافية.',
    'ثبّت قدميك باستقامة متوازنة واجعل وقفتك تعكس الجدارة والسيطرة الودودة.',
    'تقدّم نصف خطوة إلى الأمام عند طرح الفكرة المحورية لجذب انتباه المستمعين.',
    'اصمت لمدة ثانيتين بعد السؤال البلاغي وانظر مباشرة لعيون الحضور.',
  ];

  return rawParagraphs.map((paraText, idx) => {
    // 1. Tone & delivery options
    const tone = preferences.improveTone
      ? tonePool[idx % tonePool.length]
      : 'نبرة طبيعية متوازنة';
    const speedPacing = preferences.improveTone
      ? pacingPool[idx % pacingPool.length]
      : 'معتدل طبيعي';
    const pacingNote = preferences.improveTone
      ? pacingNotes[idx % pacingNotes.length]
      : '';
    const presenceTip = preferences.improveTone
      ? presenceTips[idx % presenceTips.length]
      : '';

    const suggestions: DeliverySuggestion[] = [];

    // 2. Pause and Breathing suggestions (only if enabled)
    if (preferences.suggestPauses) {
      suggestions.push({
        id: `sug-${idx}-pause-1`,
        type: 'pause',
        label: idx === 0 ? 'وقفة ترحيبية وتنفس' : 'وقفة استيعاب بعد المعنى',
        description: 'وقفة صمت بمقدار ثانية واحدة لتمكين الحضور من استيعاب العبارة وتنظيم التنفس.',
        accepted: true,
      });
    }

    // 3. Emphasis Word suggestions (only if enabled)
    let emphasisWord = '';
    if (preferences.highlightEmphasis) {
      const words = paraText.split(/\s+/);
      if (words.length > 5) {
        const targetIdx = Math.min(Math.floor(words.length / 2), words.length - 2);
        emphasisWord = words[targetIdx]?.replace(/[.,،؛!؟]/g, '') || '';
        if (emphasisWord.length >= 3) {
          suggestions.push({
            id: `sug-${idx}-emph-1`,
            type: 'emphasis',
            targetWord: emphasisWord,
            label: `تأكيد صوتي على (${emphasisWord})`,
            description: 'ارفع نبرة الصوت قليلاً مع التمهل لنقل أهمية الكلمة للمتلقي.',
            accepted: true,
          });
        }
      }
    }

    // Tone question suggestion (only if tone option enabled)
    if (
      preferences.improveTone &&
      (paraText.includes('؟') || paraText.includes('هل') || paraText.includes('كيف'))
    ) {
      suggestions.push({
        id: `sug-${idx}-tone-q`,
        type: 'tone',
        label: 'تنغيم استفهامي تصاعدي',
        description: 'ارفع نبرة الصوت في نهاية الاستفهام لجعل التساؤل حاضرًا بقوة في ذهن الجمهور.',
        accepted: true,
      });
    }

    // 4. Build annotated text
    // Step A: apply diacritics if enabled
    let annotated = preferences.addDiacritics
      ? applyArabicDiacritics(paraText)
      : paraText;

    // Step B: apply emphasis if enabled
    if (preferences.highlightEmphasis && emphasisWord && annotated.includes(emphasisWord)) {
      annotated = annotated.replace(
        emphasisWord,
        `<mark class="emphasis-word">${emphasisWord}</mark>`
      );
    }

    // Step C: apply pause markers if enabled
    if (preferences.suggestPauses) {
      if (annotated.includes('،')) {
        annotated = annotated.replace('،', '، [⏸ وقفة قصيرة] ');
      } else if (annotated.includes('.')) {
        annotated = annotated.replace('.', '. [⏸ وقفة استيعاب] ');
      }
    }

    return {
      id: `para-${Date.now()}-${idx}`,
      originalText: preferences.addDiacritics ? applyArabicDiacritics(paraText) : paraText,
      annotatedText: annotated,
      tone,
      speedPacing,
      pacingNote,
      presenceTip,
      suggestions,
    };
  });
}

